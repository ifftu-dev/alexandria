//! The issuance policy and the one rule that judges it.
//!
//! A sponsor's role carries an [`IssuancePolicy`]: bounds on the integrity
//! session behind a credential. [`evaluate`] judges the part of it a
//! verifier can see, from the credential's integrity assertion and the
//! attestation outcome a verifier established for that credential, and
//! returns the first unmet requirement as a [`PolicyRefusal`] with a stable
//! [`code`](PolicyRefusal::code). The issuing app and the hosted service
//! both call it, so a role means the same thing on a sponsor's device and in
//! the service.
//!
//! The rule trusts only what it can check. The required assurance level is
//! judged against the verified level ([`AttestationOutcome::
//! verified_assurance_level`]), never the level the assertion states, so
//! `device_attested` is met only by credential-bound evidence that verifies.
//! A floor's device attestation signal counts only when the evidence verifies
//! (credential- or session-bound: either proves the session was attested).
//! A signal the assertion lists as degraded never carries a floor: a
//! verifier cannot see how much of the session it covered.
//!
//! A role credential issued on an assessed credential is judged by
//! [`evaluate_assessed`]: its assurance comes from the
//! [`AssessedCredentialEvidence`] entry naming that credential.
//!
//! What needs the session itself stays with the issuing app: that the floor
//! judged at attempt start agrees with the one judged at issuance, and that
//! the assertion was re-derived from the session.

use serde::{Deserialize, Serialize};

use crate::assessed::AssessedCredentialEvidence;
use crate::attestation::{AttestationOutcome, VerifiedAssuranceLevel};
use crate::integrity::{ProfileSignal, TrustProfile, VerificationRung};
use crate::vc::IntegrityAssertion;

/// Where an attempt's probes come from. Set per assessment and per role (the
/// role's issuance policy); a role's policy other than `none` wins.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ProbePolicy {
    #[default]
    None,
    Reseed,
    Authored,
    Plugin,
    /// Generated by the role's model connection. Enterprise only: it needs a
    /// role whose issuance policy names the connection.
    Llm,
}

impl ProbePolicy {
    pub fn as_str(self) -> &'static str {
        match self {
            Self::None => "none",
            Self::Reseed => "reseed",
            Self::Authored => "authored",
            Self::Plugin => "plugin",
            Self::Llm => "llm",
        }
    }

    pub fn parse(s: &str) -> Result<Self, String> {
        match s {
            "none" => Ok(Self::None),
            "reseed" => Ok(Self::Reseed),
            "authored" => Ok(Self::Authored),
            "plugin" => Ok(Self::Plugin),
            "llm" => Ok(Self::Llm),
            other => Err(format!("unknown probe policy '{other}'")),
        }
    }
}

/// Bounds a credential's integrity session must meet for a role. Every field
/// is opt-in; the default policy asks for nothing. Serialized with
/// snake_case field names, the shape stored with a role.
#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
pub struct IssuancePolicy {
    /// Minimum final integrity score in `[0,1]`.
    #[serde(default)]
    pub min_integrity: Option<f64>,
    /// Maximum tolerated critical flags.
    #[serde(default)]
    pub max_critical: Option<i64>,
    /// Maximum tolerated warning flags.
    #[serde(default)]
    pub max_warning: Option<i64>,
    /// If true, the session status must be `completed` (clean): `review`,
    /// `flagged`, `suspended` and any other value are refused.
    #[serde(default)]
    pub require_clean: bool,
    /// Minimum verified assurance level: `local` (met by any credential) or
    /// `device_attested` (met only by verified credential-bound evidence).
    /// The reserved levels `anchored` and `high_assurance` have no verified
    /// path and are never met.
    #[serde(default)]
    pub required_assurance_level: Option<String>,
    /// Probe policy for attempts made for this role. Overrides the
    /// assessment's own policy when set to anything but `none`, and chooses
    /// which probes run after submission. Anything but `none` requires that
    /// the probe step ran under it and that no probe failed; a skipped probe
    /// never counts against the learner (require a satisfied one with
    /// `min_verification_rung: probed`).
    #[serde(default)]
    pub probe_policy: Option<ProbePolicy>,
    /// The model connection that writes generated probes under the `llm`
    /// policy: a saved model connection on the device that runs the attempt.
    /// Not judged by [`evaluate`].
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub probe_connection_id: Option<String>,
    /// Minimum trust profile (the policy floor).
    #[serde(default)]
    pub min_trust_profile: Option<TrustProfile>,
    /// Minimum verification rung.
    #[serde(default)]
    pub min_verification_rung: Option<VerificationRung>,
}

/// The first requirement of an [`IssuancePolicy`] a credential does not
/// meet. On the wire, `code` names the requirement and the remaining fields
/// say why.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, thiserror::Error)]
#[serde(tag = "code", rename_all = "snake_case")]
pub enum PolicyRefusal {
    #[error("issuance policy: session status is '{status}', requires 'completed'")]
    NotClean { status: String },
    #[error("issuance policy: integrity score {score:.3} below minimum {min:.3}")]
    IntegrityBelowMinimum { score: f64, min: f64 },
    #[error("issuance policy: minimum integrity required but session has no score")]
    NoIntegrityScore,
    #[error("issuance policy: {count} critical flags exceed maximum {max}")]
    TooManyCritical { count: i64, max: i64 },
    #[error("issuance policy: {count} warning flags exceed maximum {max}")]
    TooManyWarnings { count: i64, max: i64 },
    /// `level` is the verified level, not the one the assertion states.
    #[error("issuance policy: assurance level '{level}' does not meet required '{required}'")]
    AssuranceBelowRequired { level: String, required: String },
    /// `profile` is the assertion's trust profile, or `none`.
    #[error("issuance policy: trust profile '{profile}' does not meet the '{required}' floor")]
    TrustProfileBelowFloor { profile: String, required: String },
    /// `rung` is the assertion's verification rung, or `none`.
    #[error("issuance policy: verification rung '{rung}' does not meet the '{required}' minimum")]
    RungBelowMinimum { rung: String, required: String },
    #[error("issuance policy: the '{policy}' probe step did not run in the session")]
    ProbePolicyNotRun { policy: String },
    #[error("issuance policy: a '{policy}' probe failed")]
    ProbeFailed { policy: String },
}

impl PolicyRefusal {
    /// The stable code naming the unmet requirement.
    pub fn code(&self) -> &'static str {
        match self {
            Self::NotClean { .. } => "not_clean",
            Self::IntegrityBelowMinimum { .. } => "integrity_below_minimum",
            Self::NoIntegrityScore => "no_integrity_score",
            Self::TooManyCritical { .. } => "too_many_critical",
            Self::TooManyWarnings { .. } => "too_many_warnings",
            Self::AssuranceBelowRequired { .. } => "assurance_below_required",
            Self::TrustProfileBelowFloor { .. } => "trust_profile_below_floor",
            Self::RungBelowMinimum { .. } => "rung_below_minimum",
            Self::ProbePolicyNotRun { .. } => "probe_policy_not_run",
            Self::ProbeFailed { .. } => "probe_failed",
        }
    }
}

/// Judge `policy` against a credential's `integrity` assertion and the
/// `attestation` outcome a verifier established for the same credential.
/// Requirements are judged in a fixed order (status, score, flags,
/// assurance, floor, rung, probes); the first unmet one is returned.
pub fn evaluate(
    policy: &IssuancePolicy,
    integrity: &IntegrityAssertion,
    attestation: &AttestationOutcome,
) -> Result<(), PolicyRefusal> {
    judge(
        policy,
        integrity,
        attestation,
        attestation.verified_assurance_level(),
    )
}

/// [`evaluate`] for a role credential issued on an assessed credential: the
/// verified assurance level and the device attestation a floor credits are
/// the ones its [`AssessedCredentialEvidence`] entry records, the issuer's
/// signed statement of what it verified about the assessed credential. The
/// role credential's own attestation evidence (none, or session-bound: the
/// issuer's device cannot bind the candidate's session) is not judged.
/// The entry's level counts only as far as its own outcome verifies it
/// ([`AssessedCredentialEvidence::assurance_level`]).
pub fn evaluate_assessed(
    policy: &IssuancePolicy,
    integrity: &IntegrityAssertion,
    assessed: &AssessedCredentialEvidence,
) -> Result<(), PolicyRefusal> {
    judge(
        policy,
        integrity,
        &assessed.attestation,
        assessed.assurance_level(),
    )
}

fn judge(
    policy: &IssuancePolicy,
    integrity: &IntegrityAssertion,
    attestation: &AttestationOutcome,
    level: VerifiedAssuranceLevel,
) -> Result<(), PolicyRefusal> {
    let a = integrity;
    if policy.require_clean && a.status != "completed" {
        return Err(PolicyRefusal::NotClean {
            status: a.status.clone(),
        });
    }
    if let Some(min) = policy.min_integrity {
        match a.integrity_score {
            Some(score) if score >= min => {}
            Some(score) => return Err(PolicyRefusal::IntegrityBelowMinimum { score, min }),
            None => return Err(PolicyRefusal::NoIntegrityScore),
        }
    }
    if let Some(max) = policy.max_critical {
        if a.critical_count > max {
            return Err(PolicyRefusal::TooManyCritical {
                count: a.critical_count,
                max,
            });
        }
    }
    if let Some(max) = policy.max_warning {
        if a.warning_count > max {
            return Err(PolicyRefusal::TooManyWarnings {
                count: a.warning_count,
                max,
            });
        }
    }
    if let Some(required) = &policy.required_assurance_level {
        if !meets_assurance(level, required) {
            return Err(PolicyRefusal::AssuranceBelowRequired {
                level: level.as_str().to_string(),
                required: required.clone(),
            });
        }
    }
    if let Some(floor) = policy.min_trust_profile {
        let profile = a.trust_profile.as_deref().and_then(TrustProfile::parse);
        let met = profile.is_some_and(|p| {
            floor
                .signals()
                .iter()
                .all(|s| p.includes(*s) && credited(a, attestation, *s))
        });
        if !met {
            return Err(PolicyRefusal::TrustProfileBelowFloor {
                profile: a.trust_profile.clone().unwrap_or_else(|| "none".into()),
                required: floor.as_str().to_string(),
            });
        }
    }
    if let Some(required) = policy.min_verification_rung {
        let rung = a
            .verification_rung
            .as_deref()
            .and_then(VerificationRung::parse)
            .unwrap_or_default();
        if rung < required {
            return Err(PolicyRefusal::RungBelowMinimum {
                rung: a
                    .verification_rung
                    .clone()
                    .unwrap_or_else(|| VerificationRung::None.as_str().into()),
                required: required.as_str().to_string(),
            });
        }
    }
    if let Some(probe_policy) = policy.probe_policy.filter(|p| *p != ProbePolicy::None) {
        let name = probe_policy.as_str().to_string();
        match &a.probe {
            Some(p) if p.policies.contains(&name) => {
                if p.failed > 0 {
                    return Err(PolicyRefusal::ProbeFailed { policy: name });
                }
            }
            _ => return Err(PolicyRefusal::ProbePolicyNotRun { policy: name }),
        }
    }
    Ok(())
}

/// Whether the verified `level` is at least `required` on the assurance
/// ladder. Levels beyond `device_attested`, and unknown ones, are never met.
fn meets_assurance(level: VerifiedAssuranceLevel, required: &str) -> bool {
    match required {
        "local" => true,
        "device_attested" => level == VerifiedAssuranceLevel::DeviceAttested,
        _ => false,
    }
}

/// Whether `signal` counts towards a floor: the assertion says it ran and
/// was not degraded, and a device attestation's evidence verifies.
fn credited(
    a: &IntegrityAssertion,
    attestation: &AttestationOutcome,
    signal: ProfileSignal,
) -> bool {
    let name = signal.as_str();
    let ran = a.signals_run.iter().any(|s| s == name)
        && !a.signals_not_run.iter().any(|s| s == name)
        && !a.signals_degraded.iter().any(|s| s == name);
    let verified = match signal {
        ProfileSignal::DeviceAttestation => matches!(
            attestation,
            AttestationOutcome::VerifiedCredentialBound { .. }
                | AttestationOutcome::VerifiedSessionBound { .. }
        ),
        ProfileSignal::Camera => true,
    };
    ran && verified
}
