//! The issuance policy and the one rule that judges it.
//!
//! A sponsor's role carries an [`IssuancePolicy`]: bounds on the integrity
//! session behind a credential. [`evaluate`] judges the part of it a
//! verifier can see, from the credential's integrity assertion and the
//! attestation outcome a verifier established for that credential, and
//! returns the first unmet requirement as a [`PolicyRefusal`] with a stable
//! [`code`](PolicyRefusal::code). The issuing app and the hosted service
//! both call it, so a role means the same thing on a sponsor's device and in
//! the service.
//!
//! The rule trusts only what it can check. The required assurance level is
//! judged against the verified level ([`AttestationOutcome::
//! verified_assurance_level`]), never the level the assertion states, so
//! `device_attested` is met only by credential-bound evidence from the
//! attempt's own device that verifies. A paired phone's credential-bound
//! evidence verifies as `companion_attested`, which meets a required
//! `companion_attested` and never a required `device_attested`.
//! A floor's device attestation signal counts only when the evidence verifies
//! (credential- or session-bound: either proves the session was attested)
//! and comes from the device the attempt ran on. A paired phone's evidence,
//! either binding, says a genuine phone was present and nothing about the
//! desktop, so it never carries the signal.
//! The camera counts towards a floor when the assertion states its coverage
//! (`cameraCoverage`) at or above
//! [`MIN_CAMERA_COVERAGE`](crate::integrity::MIN_CAMERA_COVERAGE), even while
//! it is listed as degraded: a few windows without camera checks are
//! tolerated, and every verifier sees how many. An assertion without the
//! field (issued before it existed) gets the strict reading: a degraded
//! camera never carries a floor. Any other degraded signal never does.
//!
//! The required answer custody is judged against the custody the rule can
//! prove, not the one the assertion states: `issuer` is met only by an
//! assertion stating `issuer` beside a [`HostedAttemptEvidence`] entry that
//! says the issuer held the answers and graded ([`evaluate_hosted`]). Anyone
//! can sign an assertion stating `issuer`, a candidate with a second key
//! among them, so [`evaluate`] and [`evaluate_assessed`] credit `device`
//! whatever the assertion states. The entry is the issuer's word: a verifier
//! relies on it as far as it relies on the issuer, which for an
//! organisation's credential means its organisation backing
//! ([`crate::org::organisation_backing`]).
//! The required rung (`min_verification_rung`) is judged on the strict
//! ladder: the stated rung counts as far as the assertion shows its
//! evidence, so `probed` and every rung above it need a probe step whose
//! every probe was satisfied, and without one the rule credits `process`.
//!
//! A role credential issued on an assessed credential is judged by
//! [`evaluate_assessed`]: its assurance comes from the
//! [`AssessedCredentialEvidence`] entry naming that credential. One issued
//! from a hosted attempt is judged by [`evaluate_hosted`]: its assurance and
//! probe outcome come from the [`HostedAttemptEvidence`] entry.
//!
//! What needs the session itself stays with the issuing app: that the floor
//! judged at attempt start agrees with the one judged at issuance, and that
//! the assertion was re-derived from the session.

