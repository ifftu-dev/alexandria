    use crate::assessment::llm_probe::{self, GenerationPlan, ProbeModel};
    use alexandria_ai::{ChatRequest, Completion, FinishReason};
    use std::sync::Mutex;

    /// A model that answers its requests with `replies` in turn, repeating
    /// the last, and keeps what it was sent. Never touches the network.
    struct FakeModel {
        replies: Vec<Result<String, String>>,
        sent: Mutex<Vec<ChatRequest>>,
    }

    impl FakeModel {
        fn answering(reply: Result<&str, &str>) -> Self {
            Self::replying(&[reply])
        }

        fn replying(replies: &[Result<&str, &str>]) -> Self {
            Self {
                replies: replies
                    .iter()
                    .map(|r| r.map(str::to_owned).map_err(str::to_owned))
                    .collect(),
                sent: Mutex::new(Vec::new()),
            }
        }
    }

    impl ProbeModel for FakeModel {
        fn complete(
            &self,
            request: &ChatRequest,
        ) -> impl std::future::Future<Output = Result<Completion, String>> + Send {
            let mut sent = self.sent.lock().unwrap();
            sent.push(request.clone());
            let turn = (sent.len() - 1).min(self.replies.len() - 1);
            let reply = self.replies[turn].clone().map(|text| Completion {
                text,
                usage: None,
                finish: FinishReason::Stop,
            });
            async move { reply }
        }
    }

    const GOOD_PROBE: &str =
        r#"{"prompt":"Which follows?","options":["w","x","y","z"],"correct_index":1}"#;

    /// `setup("none")` plus a published role whose probes are generated by
    /// the on-device connection `conn`, with the attempt made for it.
    fn llm_setup(consent: bool) -> Ctx {
        let ctx = setup("none");
        alexandria_studio::store::put(
            ctx.conn(),
            "connection",
            "conn",
            0,
            &alexandria_studio::model::StudioConnection {
                id: "conn".into(),
                name: "Sponsor model".into(),
                endpoint: "http://127.0.0.1:9/v1".into(),
                model: "probe-model-1".into(),
                location: "local".into(),
                capability: "text".into(),
                enabled: true,
                has_key: false,
                context_tokens: None,
                protocol: Default::default(),
                auth: Default::default(),
            },
        )
        .unwrap();
        ctx.conn()
            .execute_batch(&format!(
                r#"
                INSERT INTO organizations (id, name, owner_address) VALUES ('org', 'Org', 'stake');
                INSERT INTO role_assessments (id, org_id, role_title, issuance_policy_json, status)
                VALUES ('role', 'org', 'SRE',
                        '{{"probe_policy":"llm","probe_connection_id":"conn"}}', 'published');
                UPDATE assessment_attempts
                   SET role_assessment_id = 'role', llm_probe_consent = {}
                 WHERE id = 'att';
                "#,
                consent as i32
            ))
            .unwrap();
        ctx
    }

