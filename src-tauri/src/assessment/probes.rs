/// What an instructor authors for an item: a follow-up (served under the
/// `authored` policy) or a seeded variant (preferred by `reseed`).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ItemProbeKind {
    FollowUp,
    Variant,
}

impl ItemProbeKind {
    fn as_str(self) -> &'static str {
        match self {
            Self::FollowUp => "follow_up",
            Self::Variant => "variant",
        }
    }

    fn parse(s: &str) -> Result<Self, String> {
        match s {
            "follow_up" => Ok(Self::FollowUp),
            "variant" => Ok(Self::Variant),
            other => Err(format!("unknown item probe kind '{other}'")),
        }
    }
}

/// A new or edited authored probe. `id` is set to edit one the actor wrote.
#[derive(Debug, Clone, Deserialize)]
pub struct ItemProbeInput {
    #[serde(default)]
    pub id: Option<String>,
    pub item_id: String,
    pub probe_kind: ItemProbeKind,
    pub content_public: serde_json::Value,
    #[serde(default)]
    pub grader_private: Option<serde_json::Value>,
    #[serde(default)]
    pub time_box_ms: Option<u64>,
}

/// An authored probe as an author sees it. `grader_private` is present only
/// on probes the viewer wrote.
#[derive(Debug, Clone, Serialize)]
pub struct ItemProbe {
    pub id: String,
    pub item_id: String,
    pub probe_kind: ItemProbeKind,
    pub content_public: serde_json::Value,
    pub grader_private: Option<serde_json::Value>,
    pub time_box_ms: Option<u64>,
    pub author_did: String,
    pub mine: bool,
    pub created_at: String,
}

fn require_instructor(conn: &rusqlite::Connection) -> Result<(), String> {
    let roles: Option<String> = conn
        .query_row(
            "SELECT account_roles FROM local_identity LIMIT 1",
            [],
            |r| r.get(0),
        )
        .optional()
        .map_err(|e| e.to_string())?;
    let roles = crate::domain::identity::roles_from_json(roles.as_deref().unwrap_or("[]"));
    if !roles.iter().any(|r| r == "instructor") {
        return Err("authoring probes needs the instructor role".into());
    }
    Ok(())
}

fn require_actor(actor_did: &str) -> Result<(), String> {
    if actor_did.is_empty() {
        return Err("no local identity".into());
    }
    Ok(())
}

/// Create or edit an authored probe. Only instructors author, only the
/// author edits, and an MCQ probe's key must grade itself as full marks, so
/// an unanswerable probe cannot be saved.
pub fn save_item_probe_db(
    db: &Database,
    actor_did: &str,
    input: &ItemProbeInput,
) -> Result<ItemProbe, String> {
    let conn = db.conn();
    require_actor(actor_did)?;
    require_instructor(conn)?;
    let item = items::load_item(db, &input.item_id)?.ok_or("assessment item not found")?;
    if !input.content_public.is_object() {
        return Err("probe content must be a JSON object".into());
    }
    if let Some(t) = input.time_box_ms {
        if !(PROBE_TIME_BOX_MIN_MS..=PROBE_TIME_BOX_MAX_MS).contains(&t) {
            return Err(format!(
                "time box must be between {PROBE_TIME_BOX_MIN_MS} and {PROBE_TIME_BOX_MAX_MS} ms"
            ));
        }
    }
    if item.item_kind == ItemKind::Mcq {
        let candidate = AssessmentItem {
            content_public: input.content_public.clone(),
            grader_private: input.grader_private.clone(),
            ..item.clone()
        };
        let content = items::grade_content(&candidate);
        let key = content
            .get("correct_indices")
            .cloned()
            .unwrap_or(serde_json::Value::Null);
        let graded = crate::assessment::mcq::score(
            &content,
            &serde_json::json!({ "selected_indices": key }),
        );
        if graded.score < 1.0 {
            return Err(format!(
                "the probe's key does not grade as a correct answer ({})",
                graded.details["kind"]
            ));
        }
    }

    let public = input.content_public.to_string();
    let private = input.grader_private.as_ref().map(|p| p.to_string());
    let time_box = input.time_box_ms.map(|t| t as i64);
    let id = match &input.id {
        Some(id) => {
            let (author, item_id): (String, String) = conn
                .query_row(
                    "SELECT author_did, item_id FROM assessment_item_probes WHERE id = ?1",
                    params![id],
                    |r| Ok((r.get(0)?, r.get(1)?)),
                )
                .optional()
                .map_err(|e| e.to_string())?
                .ok_or("authored probe not found")?;
            if author != actor_did {
                return Err("only the author can edit an authored probe".into());
            }
            if item_id != input.item_id {
                return Err("an authored probe cannot move to another item".into());
            }
            conn.execute(
                "UPDATE assessment_item_probes SET probe_kind = ?2, content_public = ?3, \
                        grader_private = ?4, time_box_ms = ?5 WHERE id = ?1",
                params![id, input.probe_kind.as_str(), public, private, time_box],
            )
            .map_err(|e| e.to_string())?;
            id.clone()
        }
        None => {
            let id = entity_id(&[
                &input.item_id,
                actor_did,
                &chrono::Utc::now().to_rfc3339_opts(chrono::SecondsFormat::Nanos, true),
            ]);
            conn.execute(
                "INSERT INTO assessment_item_probes \
                 (id, item_id, probe_kind, content_public, grader_private, time_box_ms, author_did) \
                 VALUES (?1, ?2, ?3, ?4, ?5, ?6, ?7)",
                params![
                    id,
                    input.item_id,
                    input.probe_kind.as_str(),
                    public,
                    private,
                    time_box,
                    actor_did
                ],
            )
            .map_err(|e| e.to_string())?;
            id
        }
    };
    list_item_probes_db(conn, actor_did, &input.item_id)?
        .into_iter()
        .find(|p| p.id == id)
        .ok_or_else(|| "saved probe vanished".to_string())
}

/// Authored probes for an item, oldest first. Keys are shown only to their
/// author.
pub fn list_item_probes_db(
    conn: &rusqlite::Connection,
    actor_did: &str,
    item_id: &str,
) -> Result<Vec<ItemProbe>, String> {
    require_actor(actor_did)?;
    require_instructor(conn)?;
    let mut stmt = conn
        .prepare(
            "SELECT id, item_id, probe_kind, content_public, grader_private, time_box_ms, \
                    author_did, created_at \
               FROM assessment_item_probes WHERE item_id = ?1 ORDER BY created_at, id",
        )
        .map_err(|e| e.to_string())?;
    let rows = stmt
        .query_map(params![item_id], |r| {
            Ok((
                r.get::<_, String>(0)?,
                r.get::<_, String>(1)?,
                r.get::<_, String>(2)?,
                r.get::<_, String>(3)?,
                r.get::<_, Option<String>>(4)?,
                r.get::<_, Option<i64>>(5)?,
                r.get::<_, String>(6)?,
                r.get::<_, String>(7)?,
            ))
        })
        .map_err(|e| e.to_string())?
        .collect::<Result<Vec<_>, _>>()
        .map_err(|e| e.to_string())?;
    rows.into_iter()
        .map(
            |(id, item_id, kind, public, private, time_box, author, created_at)| {
                let mine = author == actor_did;
                Ok(ItemProbe {
                    id,
                    item_id,
                    probe_kind: ItemProbeKind::parse(&kind)?,
                    content_public: serde_json::from_str(&public).map_err(|e| e.to_string())?,
                    grader_private: private
                        .filter(|_| mine)
                        .map(|p| serde_json::from_str(&p))
                        .transpose()
                        .map_err(|e| e.to_string())?,
                    time_box_ms: time_box.and_then(|t| u64::try_from(t).ok()),
                    author_did: author,
                    mine,
                    created_at,
                })
            },
        )
        .collect()
}

/// Delete an authored probe the actor wrote. Probes already served keep the
/// copy they were served with.
pub fn delete_item_probe_db(
    conn: &rusqlite::Connection,
    actor_did: &str,
    probe_id: &str,
) -> Result<(), String> {
    require_actor(actor_did)?;
    require_instructor(conn)?;
    let changed = conn
        .execute(
            "DELETE FROM assessment_item_probes WHERE id = ?1 AND author_did = ?2",
            params![probe_id, actor_did],
        )
        .map_err(|e| e.to_string())?;
    if changed == 0 {
        return Err("authored probe not found, or written by another author".into());
    }
    Ok(())
}

