/// What starting the probe step needs next.
#[derive(Debug)]
pub enum ProbeStart {
    /// The probes to show (possibly none); everything else is recorded.
    Served(Vec<ServedProbe>),
    /// Generated probes: run the plan's requests against its connection with
    /// no database lock held, then store the answers with
    /// [`crate::assessment::llm_probe::store_generated_db`].
    Generate(Box<crate::assessment::llm_probe::GenerationPlan>),
}

/// A probe as the client sees it: the public half only, MCQ options in this
