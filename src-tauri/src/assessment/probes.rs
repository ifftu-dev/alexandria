pub(crate) struct Generated {
    pub(crate) source: &'static str,
    pub(crate) source_id: Option<String>,
    pub(crate) question: serde_json::Value,
    pub(crate) expectation: Option<serde_json::Value>,
    pub(crate) time_box_ms: u64,
    pub(crate) pass_score: f64,
    /// How a generated probe was made; copied into every result recorded
    /// for it. `None` for every other source.
    pub(crate) generation: Option<serde_json::Value>,
}

enum Generation {
    Probe(Generated),
    Skipped(&'static str, serde_json::Value),
}

struct AuthoredRow {
    id: String,
    content_public: serde_json::Value,
    grader_private: Option<serde_json::Value>,
    time_box_ms: Option<u64>,
}

/// Authored probes of `kind` for an item, excluding any written by `subject`.
fn authored_for(
    conn: &rusqlite::Connection,
    item_id: &str,
    kind: &str,
    subject_did: &str,
) -> Result<Vec<AuthoredRow>, String> {
    let mut stmt = conn
        .prepare(
            "SELECT id, content_public, grader_private, time_box_ms FROM assessment_item_probes \
              WHERE item_id = ?1 AND probe_kind = ?2 AND author_did != ?3 ORDER BY id",
        )
        .map_err(|e| e.to_string())?;
    let rows = stmt
        .query_map(params![item_id, kind, subject_did], |r| {
            Ok((
                r.get::<_, String>(0)?,
                r.get::<_, String>(1)?,
                r.get::<_, Option<String>>(2)?,
                r.get::<_, Option<i64>>(3)?,
            ))
        })
        .map_err(|e| e.to_string())?
        .collect::<Result<Vec<_>, _>>()
        .map_err(|e| e.to_string())?;
    rows.into_iter()
        .map(|(id, public, private, time_box)| {
            Ok(AuthoredRow {
                id,
                content_public: serde_json::from_str(&public).map_err(|e| e.to_string())?,
                grader_private: private
                    .map(|p| serde_json::from_str(&p))
                    .transpose()
                    .map_err(|e| e.to_string())?,
                time_box_ms: time_box.and_then(|t| u64::try_from(t).ok()),
            })
        })
        .collect()
}

fn from_authored(source: &'static str, row: AuthoredRow, time_box_ms: u64) -> Generated {
    Generated {
        source,
        source_id: Some(row.id),
        question: row.content_public,
        expectation: row.grader_private,
        time_box_ms: row.time_box_ms.unwrap_or(time_box_ms),
        pass_score: 1.0,
        generation: None,
    }
}

#[allow(clippy::too_many_arguments)]
fn generate(
    db: &Database,
    engine: &GradeEngine<'_>,
    policy: ProbePolicy,
    ctx: &AttemptCtx,
    item: &AssessmentItem,
    submission: &serde_json::Value,
    option_order: &[usize],
    rng: &mut SplitMix64,
) -> Result<Generation, String> {
    let conn = db.conn();
    let generated = match policy {
        ProbePolicy::None => return Ok(Generation::Skipped(skip_reason::POLICY_NONE, json_null())),
        ProbePolicy::Reseed => {
            let time_box = per_item_ms(ctx)
                .map(|ms| ms.saturating_mul(3) / 2)
                .unwrap_or(DEFAULT_AUTHORED_TIME_BOX_MS)
                .clamp(RESEED_TIME_BOX_MIN_MS, RESEED_TIME_BOX_MAX_MS);
            let mut variants = authored_for(conn, &item.id, "variant", &ctx.subject_did)?;
            if variants.is_empty() {
                Generated {
                    source: "reseed",
                    source_id: None,
                    question: item.content_public.clone(),
                    expectation: item.grader_private.clone(),
                    time_box_ms: time_box,
                    pass_score: 1.0,
                    generation: None,
                }
            } else {
                let pick = rng.below(variants.len());
                from_authored("variant", variants.swap_remove(pick), time_box)
            }
        }
        ProbePolicy::Authored => {
            let mut follow_ups = authored_for(conn, &item.id, "follow_up", &ctx.subject_did)?;
            if follow_ups.is_empty() {
                return Ok(Generation::Skipped(
                    skip_reason::NO_AUTHORED_PROBE,
                    json_null(),
                ));
            }
            let pick = rng.below(follow_ups.len());
            from_authored(
                "authored",
                follow_ups.swap_remove(pick),
                DEFAULT_AUTHORED_TIME_BOX_MS,
            )
        }
        // Generated probes need network I/O and never reach this
        // database-bound path: `start_probes_db` returns a plan instead.
        ProbePolicy::Llm => {
            return Ok(Generation::Skipped(
                skip_reason::PROVIDER_UNAVAILABLE,
                json_null(),
            ))
        }
        ProbePolicy::Plugin => {
            let seed = rng.next_u64();
            match items::probe_item(db, engine, item, submission, Some(option_order), seed) {
                Ok(Some(record)) => Generated {
                    source: "plugin",
                    source_id: None,
                    question: record.question,
                    expectation: (!record.expectation.is_null()).then_some(record.expectation),
                    time_box_ms: record.time_box_ms,
                    pass_score: record.pass_score,
                    generation: None,
                },
                Ok(None) => {
                    return Ok(Generation::Skipped(
                        skip_reason::PROVIDER_UNAVAILABLE,
                        json_null(),
                    ))
                }
                Err(e) => {
                    return Ok(Generation::Skipped(
                        skip_reason::PROVIDER_UNAVAILABLE,
                        serde_json::json!(e),
                    ))
                }
            }
        }
    };
    Ok(Generation::Probe(Generated {
        time_box_ms: generated
            .time_box_ms
            .clamp(PROBE_TIME_BOX_MIN_MS, PROBE_TIME_BOX_MAX_MS),
        ..generated
    }))
}

fn json_null() -> serde_json::Value {
    serde_json::Value::Null
}

/// A result's detail with the generated probe's record (model id, prompt
/// hash, latency) attached, so it enters the commitment chain with every
/// result recorded for that probe.
trait WithGeneration {
    fn with_generation(self, generation: &Option<serde_json::Value>) -> Self;
}

impl WithGeneration for serde_json::Value {
    fn with_generation(mut self, generation: &Option<serde_json::Value>) -> Self {
        if let (Some(g), Some(obj)) = (generation, self.as_object_mut()) {
            obj.insert("generation".into(), g.clone());
        }
        self
    }
}

