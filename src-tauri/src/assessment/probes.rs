//! Probes: short follow-ups produced from the learner's own submission, run
//! inside the integrity session after an attempt is submitted and before
//! monitoring ends.
//!
//! A probe is graded by the same grader contract as the item it follows, so
//! Sentinel never knows the item format. The policy decides where the probe
//! comes from:
//!
//! * `reseed` — the same item again with a fresh option order, or one of the
//!   item's authored seeded variants, with a time box proportional to the
//!   time the learner spent per item in the attempt.
//! * `authored` — an instructor-written follow-up for the item.
//! * `plugin` — the item's grader generates one from the submission through
//!   its optional probe export (see [`crate::plugins::grade_contract`]).
//! * `llm` — a sponsor-configured model connection writes one from the
//!   learner's answer and the skill description (see
//!   [`crate::assessment::llm_probe`]). Starting probes then returns a
//!   [`ProbeStart::Generate`] plan; the caller runs the model with no
//!   database lock held and stores the result.
//! * `none` — no probe.
//!
//! Only items the learner answered with full marks are probed: a probe
//! verifies that a correct answer was the learner's own, and failing a probe
//! on an item already answered wrongly would say nothing about misconduct.
//!
//! Every outcome is recorded through [`crate::sentinel::verification`] into
//! the session's commitment chain. Skipped (time box ran out, no probe
//! available, nothing eligible, policy `none`) never counts against the
//! learner. Authored probes written by the learner being probed are never
//! served to them.
//!
//! The time box starts when the probe renders, on the host clock. Latency to
//! render, to first input and to answer is kept with the result as a
//! response-process input.
//!
//! Credential authority is unchanged (ADR-0003): a probe runs on the item's
//! own CID-verified grader and grants nothing by itself.

