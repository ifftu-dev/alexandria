const PROBE_COLUMNS: &str = "id, attempt_id, item_id, policy, source, item_kind, plugin_cid, \
     question_json, expectation_json, option_order, time_box_ms, pass_score, rendered_at_ms, \
     outcome, generation_json";

fn map_probe(r: &rusqlite::Row<'_>) -> rusqlite::Result<ProbeRow> {
    let bad = |i: usize, e: String| {
        rusqlite::Error::FromSqlConversionFailure(i, rusqlite::types::Type::Text, e.into())
    };
    let kind: String = r.get(5)?;
    let question: String = r.get(7)?;
    let expectation: Option<String> = r.get(8)?;
    let order: Option<String> = r.get(9)?;
    let generation: Option<String> = r.get(14)?;
    Ok(ProbeRow {
        id: r.get(0)?,
        attempt_id: r.get(1)?,
        item_id: r.get(2)?,
        policy: r.get(3)?,
        source: r.get(4)?,
        item_kind: ItemKind::parse(&kind).map_err(|e| bad(5, e))?,
        plugin_cid: r.get(6)?,
        question: serde_json::from_str(&question).map_err(|e| bad(7, e.to_string()))?,
        expectation: expectation
            .map(|e| serde_json::from_str(&e))
            .transpose()
            .map_err(|e| bad(8, e.to_string()))?,
        option_order: order
            .map(|o| serde_json::from_str(&o))
            .transpose()
            .map_err(|e| bad(9, e.to_string()))?,
        time_box_ms: r.get::<_, i64>(10)?.max(0) as u64,
        pass_score: r.get(11)?,
        rendered_at_ms: r.get(12)?,
        outcome: r.get(13)?,
        generation: generation
            .map(|g| serde_json::from_str(&g))
            .transpose()
            .map_err(|e| bad(14, e.to_string()))?,
    })
}

fn load_probe(conn: &rusqlite::Connection, probe_id: &str) -> Result<ProbeRow, String> {
    conn.query_row(
        &format!("SELECT {PROBE_COLUMNS} FROM assessment_probes WHERE id = ?1"),
        params![probe_id],
        map_probe,
    )
    .map_err(|e| match e {
        rusqlite::Error::QueryReturnedNoRows => "probe not found".to_string(),
        other => other.to_string(),
    })
}

pub(crate) fn probes_for(
    conn: &rusqlite::Connection,
    attempt_id: &str,
) -> Result<Vec<ProbeRow>, String> {
    let mut stmt = conn
        .prepare(&format!(
            "SELECT {PROBE_COLUMNS} FROM assessment_probes WHERE attempt_id = ?1 ORDER BY ordinal"
        ))
        .map_err(|e| e.to_string())?;
    let rows = stmt
        .query_map(params![attempt_id], map_probe)
        .map_err(|e| e.to_string())?
        .collect::<Result<Vec<_>, _>>()
        .map_err(|e| e.to_string())?;
    Ok(rows)
}

/// The probe as an item, so it is served and graded by exactly the item
/// paths: the content split, MCQ shuffling and the reproducibility triple.
fn as_item(p: &ProbeRow) -> AssessmentItem {
    AssessmentItem {
        id: p.id.clone(),
        item_kind: p.item_kind,
        skill_id: String::new(),
        plugin_cid: p.plugin_cid.clone(),
        content_public: p.question.clone(),
        grader_private: p.expectation.clone(),
        difficulty: 1,
        points: 1.0,
    }
}

pub(crate) fn served(p: &ProbeRow, now_ms: i64) -> ServedProbe {
    let view = items::served_item(&as_item(p), p.option_order.as_deref());
    ServedProbe {
        id: p.id.clone(),
        item_kind: p.item_kind,
        content: view.content,
        time_box_ms: p.time_box_ms,
        remaining_ms: p.rendered_at_ms.map(|at| {
            let elapsed = now_ms.saturating_sub(at).max(0) as u64;
            p.time_box_ms.saturating_sub(elapsed)
        }),
    }
}

fn session_of(conn: &rusqlite::Connection, attempt_id: &str) -> Result<String, String> {
    conn.query_row(
        "SELECT integrity_session_id FROM assessment_attempts WHERE id = ?1",
        params![attempt_id],
        |r| r.get::<_, Option<String>>(0),
    )
    .map_err(|e| e.to_string())?
    .ok_or_else(|| "assessment has no integrity session".to_string())
}

/// Record one probe-step result. Every argument is a field of the record, so
/// a struct would only rename them.
#[allow(clippy::too_many_arguments)]
pub(crate) fn record_probe_step(
    conn: &rusqlite::Connection,
    session_id: &str,
    attempt_id: &str,
    policy: &str,
    outcome: VerificationOutcome,
    reason: Option<&str>,
    subject_ref: Option<&str>,
    detail: serde_json::Value,
) -> Result<(), String> {
    record_verification(
        conn,
        &NewVerification {
            session_id,
            attempt_id: Some(attempt_id),
            step: STEP_PROBE,
            policy,
            outcome,
            reason,
            subject_ref,
            detail,
        },
    )
    .map(|_| ())
}

