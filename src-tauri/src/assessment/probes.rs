// ---- policy ---------------------------------------------------------------

/// The probe policy in force for an attempt: the role's when the attempt is
/// for a role whose policy is not `none`, otherwise the assessment's.
pub fn effective_probe_policy(
    conn: &rusqlite::Connection,
    attempt_id: &str,
) -> Result<ProbePolicy, String> {
    let (bank_policy, role_policy_json): (String, Option<String>) = conn
        .query_row(
            "SELECT qb.probe_policy, ra.issuance_policy_json \
               FROM assessment_attempts a \
               JOIN question_banks qb ON qb.id = a.bank_id \
               LEFT JOIN role_assessments ra ON ra.id = a.role_assessment_id \
              WHERE a.id = ?1",
            params![attempt_id],
            |r| Ok((r.get(0)?, r.get(1)?)),
        )
        .map_err(|e| match e {
            rusqlite::Error::QueryReturnedNoRows => "attempt not found".to_string(),
            other => other.to_string(),
        })?;
    if let Some(json) = role_policy_json {
        let policy: crate::credentials::IssuancePolicy = serde_json::from_str(&json)
            .map_err(|e| format!("role issuance policy is unreadable: {e}"))?;
        if let Some(p) = policy.probe_policy.filter(|p| *p != ProbePolicy::None) {
            return Ok(p);
        }
    }
    ProbePolicy::parse(&bank_policy)
}

// ---- attempt context ------------------------------------------------------

/// The attempt belongs to `actor_did`. Probes are answered by the learner
/// who made the attempt and no one else.
pub(crate) fn ensure_attempt_owner(
    conn: &rusqlite::Connection,
    attempt_id: &str,
    actor_did: &str,
) -> Result<(), String> {
    if actor_did.is_empty() {
        return Err("no local identity".into());
    }
    let owner: String = conn
        .query_row(
            "SELECT subject_did FROM assessment_attempts WHERE id = ?1",
            params![attempt_id],
            |r| r.get(0),
        )
        .map_err(|e| match e {
            rusqlite::Error::QueryReturnedNoRows => "attempt not found".to_string(),
            other => other.to_string(),
        })?;
    if owner != actor_did {
        return Err("assessment attempt belongs to another learner".into());
    }
    Ok(())
}

/// Probes run inside the attempt's monitoring session, never after it.
pub(crate) fn require_live_session(
    conn: &rusqlite::Connection,
    session_id: &str,
) -> Result<(), String> {
    let live: bool = conn
        .query_row(
            "SELECT ended_at IS NULL FROM integrity_sessions WHERE id = ?1",
            params![session_id],
            |r| r.get(0),
        )
        .optional()
        .map_err(|e| e.to_string())?
        .unwrap_or(false);
    if !live {
        return Err("assessment monitoring session is missing or already ended".into());
    }
    Ok(())
}

