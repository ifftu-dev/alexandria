/// Where an attempt's probes come from. Set per assessment
/// (`question_banks.probe_policy`) and per role (the role's issuance policy);
/// a role's policy other than `none` wins.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ProbePolicy {
    #[default]
    None,
    Reseed,
    Authored,
    Plugin,
    /// Generated by the role's model connection. Enterprise only: it needs
    /// a role whose issuance policy names the connection.
    Llm,
}

impl ProbePolicy {
    pub fn as_str(self) -> &'static str {
        match self {
            Self::None => "none",
            Self::Reseed => "reseed",
            Self::Authored => "authored",
            Self::Plugin => "plugin",
            Self::Llm => "llm",
        }
    }

    pub fn parse(s: &str) -> Result<Self, String> {
        match s {
            "none" => Ok(Self::None),
            "reseed" => Ok(Self::Reseed),
            "authored" => Ok(Self::Authored),
            "plugin" => Ok(Self::Plugin),
            "llm" => Ok(Self::Llm),
            other => Err(format!("unknown probe policy '{other}'")),
        }
    }
}

