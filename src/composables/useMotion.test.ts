import { expect, test, vi } from 'vitest'

test('device preference survives reload and the OS can reduce system motion', async () => {
  localStorage.clear()
  const query = new EventTarget()
  Object.assign(query, { matches: false })
  vi.stubGlobal('matchMedia', () => query)
  const { useMotion } = await import('./useMotion')
  const motion = useMotion()
  expect(motion.mode.value).toBe('full')
  motion.setPreference('off')
  expect(motion.mode.value).toBe('off')
  vi.resetModules()
  const reloaded = (await import('./useMotion')).useMotion()
  expect(reloaded.preference.value).toBe('off')
  reloaded.setPreference('system')
  Object.assign(query, { matches: true })
  query.dispatchEvent(new Event('change'))
  expect(reloaded.mode.value).toBe('reduced')
  reloaded.setPreference('off')
  expect(reloaded.mode.value).toBe('off')
  reloaded.setPreference('reduced')
  Object.assign(query, { matches: false })
  query.dispatchEvent(new Event('change'))
  expect(reloaded.mode.value).toBe('reduced')
  vi.unstubAllGlobals()
})

test('returning to the app rechecks the OS preference and cancels an in-flight effect', async () => {
  vi.resetModules()
  localStorage.clear()
  const query = Object.assign(new EventTarget(), { matches: false })
  vi.stubGlobal('matchMedia', () => query)
  const animation = Object.assign(new EventTarget(), { cancel: vi.fn() })
  const element = document.createElement('div')
  element.animate = vi.fn(() => animation as unknown as Animation)
  const { useMotion, animateMotion } = await import('./useMotion')
  const motion = useMotion()
  animateMotion(element, [{ opacity: 0 }, { opacity: 1 }])
  Object.assign(query, { matches: true })
  window.dispatchEvent(new Event('focus'))
  expect(motion.mode.value).toBe('reduced')
  expect(animation.cancel).toHaveBeenCalled()
  vi.unstubAllGlobals()
})
